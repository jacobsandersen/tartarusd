#!/usr/bin/env python3
"""Generate crates/core/src/keys_table.rs from linux/input-event-codes.h.

Run: python3 -I tools/gen_keys.py > crates/core/src/keys_table.rs
"""
import re

SKIP = {"KEY_MAX", "KEY_CNT", "KEY_MIN_INTERESTING", "BTN_MISC", "BTN_MOUSE",
        "BTN_JOYSTICK", "BTN_GAMEPAD", "BTN_DIGI", "BTN_WHEEL",
        "BTN_TRIGGER_HAPPY"}
out = []
for line in open("/usr/include/linux/input-event-codes.h"):
    m = re.match(r"#define\s+((?:KEY|BTN)_\w+)\s+(0x[0-9a-fA-F]+|\d+)\b", line)
    if m and m.group(1) not in SKIP and not m.group(1).endswith(("_MAX", "_CNT")):
        out.append((m.group(1), int(m.group(2), 0)))
print("// @generated by tools/gen_keys.py from linux/input-event-codes.h. Do not edit.")
print("pub(crate) static KEY_TABLE: &[(&str, u16)] = &[")
for n, c in out:
    print(f'    ("{n}", {c}),')
print("];")
